function getFewShotExamples(currentStage) {
  switch (currentStage) {
    case 'welcome':
    case 'check_in':
      return EXAMPLES.friendCold;
    case 'safety':
      return EXAMPLES.anniversary;
    case 'awareness':
      return EXAMPLES.workReport;
    case 'socratic':
    case 'rebuild':
      return EXAMPLES.anniversary;
    case 'regulation':
    case 'closing':
    case 'rating':
      return EXAMPLES.insomnia;
    default:
      return EXAMPLES.friendCold;
  }
}

